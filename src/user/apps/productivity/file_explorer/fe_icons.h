/* Draw one embedded icon at (x,y): alpha already folded into the pixels,
 * so a plain copy is enough. Returns 0 if the name is unknown. */
static int fe_icon_draw(const char* name, uint32_t* fb, int fw, int fh,
                        int x, int y) {
    for (int i = 0; fe_icons[i].name; i++) {
        if (((name[0]^fe_icons[i].name[0]) | (name[1]^fe_icons[i].name[1])) == 0
            && strcmp(name, fe_icons[i].name) == 0) {
            const unsigned char* p = fe_icons[i].px;
            for (int dy = 0; dy < 16; dy++)
                for (int dx = 0; dx < 16; dx++) {
                    int xx = x + dx, yy = y + dy;
                    if (xx < 0 || yy < 0 || xx >= fw || yy >= fh) continue;
                    uint32_t c = (p[0] << 16) | (p[1] << 8) | p[2];
                    if (c) fb[yy * fw + xx] = c;
                    p += 3;
                }
            return 1;
        }
    }
    return 0;
}

